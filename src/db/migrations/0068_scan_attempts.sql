-- Tenant isolation, matching every other tenant table. Defence in depth: the
-- repository also scopes by organization_id, because the app connects as the
-- schema owner and Postgres skips RLS for that role.
DO $$
BEGIN
  EXECUTE 'ALTER TABLE scan_attempts ENABLE ROW LEVEL SECURITY';
  EXECUTE
    'CREATE POLICY tenant_isolation ON scan_attempts FOR ALL '
    'USING (organization_id = current_setting(''app.current_org'', true)::bigint) '
    'WITH CHECK (organization_id = current_setting(''app.current_org'', true)::bigint)';
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;
