-- The door-incident report reads one event's night newest-first. Counts per
-- outcome come off this same index and are filtered, rather than getting an
-- index of their own: an event's whole night is a few thousand rows, so a
-- second index would be paid on every single scan to save a filter over a set
-- that small.
CREATE INDEX IF NOT EXISTS "ix_scan_attempts_event"
  ON "scan_attempts" USING btree ("organization_id", "event_id", "scanned_at");
--> statement-breakpoint
-- "Was it one broken pass or forty different bad codes?" — the question the
-- fingerprint exists to answer, and a GROUP BY needs the index to answer it.
CREATE INDEX IF NOT EXISTS "ix_scan_attempts_token"
  ON "scan_attempts" USING btree ("organization_id", "token_fingerprint");
--> statement-breakpoint
-- Settling one disputed entry: every scan this ticket was ever part of.
CREATE INDEX IF NOT EXISTS "ix_scan_attempts_ticket"
  ON "scan_attempts" USING btree ("ticket_id");
