-- The workspace's Google Calendar connection (US-MTG-08), one row per
-- organization. Until now nothing held one: meetings were saved with
-- `sync_status = 'pending'` and an outbox event, and no consumer could ever
-- send the invite, because there was no calendar to send it from. An Admin
-- connects on Settings -> Integrations; eventa-worker then uses this row to
-- create, move and cancel each meeting's Google event (US-MTG-04/05/06).
--
-- No row means disconnected, so a workspace that never connects costs nothing.
-- `status` is 'expired' once Google stops accepting the grant (revoked by the
-- account, or a Testing-mode token past its 7 days); the worker sets it, and
-- the Admin is prompted to reconnect instead of sync failing silently.
--
-- The refresh token and the pending PKCE verifier are stored ENCRYPTED (bytea,
-- `iv | authTag | ciphertext`, AES-256-GCM under SECRET_ENCRYPTION_KEY) by the
-- same cipher that protects the Stripe keys and TOTP seeds. They are
-- write-only from the API's point of view: nothing reads them back to a
-- response. eventa-worker decrypts the token with the SAME key to call Google.
--
-- The `oauth_state_*` columns are one pending connect: the SHA-256 of the
-- nonce Google echoes back in `state` (never the nonce itself), who started
-- it, and a ten-minute expiry on the database clock. The first matching
-- callback clears them, which is what makes a state single-use.
-- `oauth_state_user_id` is deliberately NOT a foreign key: it lives ten
-- minutes at most and is cleared on first use.
--
-- `ck_calendar_connections_token` holds the one invariant the worker relies
-- on: a connected row always has a token to sync with.
--
-- Creates a new enum type and uses it in the same transaction, which Postgres
-- allows (only a value ADDED to an existing enum is unusable until commit).
